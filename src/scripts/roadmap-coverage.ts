/**
 * `npm run roadmap:coverage`
 *
 * Reports how completely the curriculum is classified for every career track
 * and writes `reports/roadmap-coverage.json` plus a Markdown summary.
 */
import "dotenv/config";
import * as fs from "fs";
import * as path from "path";
import { occurrences, phaseOrder, taxonomy, tracks } from "../lib/roadmap/config";
import { trackStats } from "../lib/roadmap/tracks";
import { validateRoadmapConfig } from "../lib/roadmap/validation";
import type { TrackId } from "../lib/roadmap/types";

const ROOT = process.cwd();
const OUT_DIR = path.join(ROOT, "reports");

interface TrackCoverage {
  trackId: TrackId;
  name: string;
  classified: number;
  unclassified: number;
  coveragePercent: number;
  core: number;
  important: number;
  optional: number;
  skip: number;
  coreHours: number;
  requiredHours: number;
  allHours: number;
  phasesIncluded: number;
}

function buildCoverage(): {
  totalOccurrences: number;
  totalCanonical: number;
  phases: number;
  skills: number;
  tracks: TrackCoverage[];
} {
  const tracks_ = tracks.map((track): TrackCoverage => {
    const stats = trackStats(track.id);
    const classified = occurrences.filter(
      (occurrence) => occurrence.importance[track.id] !== undefined
    ).length;
    return {
      trackId: track.id,
      name: track.name,
      classified,
      unclassified: occurrences.length - classified,
      coveragePercent: Math.round((classified / Math.max(1, occurrences.length)) * 100),
      core: stats.core,
      important: stats.important,
      optional: stats.optional,
      skip: stats.skip,
      coreHours: stats.coreHours,
      requiredHours: stats.requiredHours,
      allHours: stats.allHours,
      phasesIncluded: stats.phases.length,
    };
  });

  return {
    totalOccurrences: occurrences.length,
    totalCanonical: new Set(occurrences.map((o) => o.canonicalLessonKey)).size,
    phases: phaseOrder.length,
    skills: taxonomy.skills.length,
    tracks: tracks_,
  };
}

function toMarkdown(coverage: ReturnType<typeof buildCoverage>, validationOk: boolean): string {
  const lines: string[] = [];
  lines.push("# Roadmap Coverage");
  lines.push("");
  lines.push(`Generated by \`npm run roadmap:coverage\` — configuration valid: **${validationOk ? "yes" : "no"}**.`);
  lines.push("");
  lines.push(`- Curriculum occurrences: **${coverage.totalOccurrences}**`);
  lines.push(`- Canonical lessons: **${coverage.totalCanonical}**`);
  lines.push(`- Phases: **${coverage.phases}**`);
  lines.push(`- Skills in taxonomy: **${coverage.skills}**`);
  lines.push("");
  lines.push("| Track | Core | Important | Optional | Skip | Coverage | Core hours | Required hours |");
  lines.push("| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |");
  for (const track of coverage.tracks) {
    lines.push(
      `| ${track.name} | ${track.core} | ${track.important} | ${track.optional} | ${track.skip} | ${track.coveragePercent}% | ${track.coreHours}h | ${track.requiredHours}h |`
    );
  }
  lines.push("");
  lines.push("## Notes");
  lines.push("");
  lines.push("- Counts are canonical lessons: duplicate curriculum locations share one identity.");
  lines.push("- Hours use upstream curriculum durations where available.");
  lines.push("- Classification lives in `roadmaps/tracks/*.json`; regenerate metadata with `npm run roadmap:metadata`.");
  lines.push("");
  return lines.join("\n");
}

function main() {
  const report = validateRoadmapConfig();
  const coverage = buildCoverage();

  fs.mkdirSync(OUT_DIR, { recursive: true });
  const jsonPath = path.join(OUT_DIR, "roadmap-coverage.json");
  const mdPath = path.join(OUT_DIR, "roadmap-coverage.md");

  fs.writeFileSync(
    jsonPath,
    `${JSON.stringify(
      {
        generatedAt: new Date().toISOString(),
        valid: report.ok,
        validationWarnings: report.warnings,
        ...coverage,
      },
      null,
      2
    )}\n`,
    "utf8"
  );
  fs.writeFileSync(mdPath, toMarkdown(coverage, report.ok), "utf8");

  console.log("Roadmap coverage");
  console.log("----------------");
  console.log(
    `Occurrences ${coverage.totalOccurrences} · canonical ${coverage.totalCanonical} · phases ${coverage.phases} · skills ${coverage.skills}`
  );
  for (const track of coverage.tracks) {
    console.log(
      `${track.name.padEnd(30)} core ${String(track.core).padStart(3)} · important ${String(
        track.important
      ).padStart(3)} · optional ${String(track.optional).padStart(3)} · skip ${String(
        track.skip
      ).padStart(3)} · coverage ${track.coveragePercent}% · required ${track.requiredHours}h`
    );
  }
  console.log(`\nWrote ${path.relative(ROOT, jsonPath)} and ${path.relative(ROOT, mdPath)}`);

  if (!report.ok) {
    console.error("Configuration invalid — run npm run roadmap:validate for details.");
    process.exit(1);
  }
}

try {
  main();
} catch (error) {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
}
